from __future__ import annotations

import configparser
import json
import os
import secrets
from pathlib import Path
from uuid import uuid4

import psycopg
import pytest
from psycopg import sql
from psycopg.conninfo import make_conninfo
from pydantic import SecretStr

from db_operator.config import Settings
from db_operator.service import Service

ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def lab_case(tmp_path, monkeypatch):
    env_path = ROOT / "runtime/lab/environment.json"
    if os.environ.get("RUN_DB_OPERATOR_INTEGRATION") != "1":
        pytest.skip("Run make lab-up and RUN_DB_OPERATOR_INTEGRATION=1 uv run pytest")
    env = json.loads(env_path.read_text())
    for key, value in env.items():
        monkeypatch.setenv(key, value)
    suffix = uuid4().hex[:12]
    database, writer, alias = "case_" + suffix, "writer_" + suffix, "case_" + suffix
    password = secrets.token_urlsafe(24)
    cfg = json.loads(Path(env["DB_OPERATOR_REGISTRY"]).read_text())
    for node in ["source", "target"]:
        base = env["LAB_" + node.upper() + "_ADMIN"]
        with psycopg.connect(base, autocommit=True) as conn:
            conn.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database)))
            conn.execute(
                sql.SQL("CREATE ROLE {} {} PASSWORD {}").format(
                    sql.Identifier(writer),
                    sql.SQL("LOGIN" if node == "source" else "NOLOGIN"),
                    sql.Literal(password),
                )
            )
        dsn = make_conninfo(base, dbname=database)
        monkeypatch.setenv("LAB_" + node.upper() + "_ADMIN", dsn)
        monkeypatch.setenv(
            "LAB_" + node.upper() + "_REPL",
            make_conninfo(env["LAB_" + node.upper() + "_REPL"], dbname=database),
        )
        db = cfg["databases"]["resource:" + node]
        db.update(identity="test-" + node + suffix, database=database, writer_role=writer)
        with psycopg.connect(dsn, autocommit=True) as conn:
            conn.execute(
                "CREATE TABLE inventory(sku text PRIMARY KEY,stock integer NOT NULL "
                "CHECK(stock>=0));CREATE TABLE orders(id bigint GENERATED BY DEFAULT AS IDENTITY "
                "PRIMARY KEY,request_id uuid NOT NULL UNIQUE,sku text NOT NULL REFERENCES "
                "inventory(sku));ALTER TABLE inventory OWNER TO app_owner;ALTER TABLE orders "
                "OWNER TO app_owner;GRANT USAGE ON SCHEMA public TO replicator;GRANT SELECT ON "
                "inventory,orders TO replicator"
            )
            conn.execute(
                sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(sql.Identifier(writer))
            )
            conn.execute(
                sql.SQL("GRANT SELECT,INSERT,UPDATE,DELETE ON inventory,orders TO {}").format(
                    sql.Identifier(writer)
                )
            )
            conn.execute(
                sql.SQL("GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO {}").format(
                    sql.Identifier(writer)
                )
            )
            if node == "source":
                conn.execute("INSERT INTO inventory VALUES('chiikawa',1000)")
                for _ in range(10):
                    conn.execute(
                        "INSERT INTO orders(request_id,sku) VALUES (%s,'chiikawa')", (uuid4(),)
                    )
                conn.execute("UPDATE inventory SET stock=990")
    manager_role = "manager_" + suffix
    manager_password = secrets.token_urlsafe(24)
    manager = make_conninfo(
        env["DB_OPERATOR_MANAGEMENT_DSN"],
        dbname=database,
        user=manager_role,
        password=manager_password,
    )
    with psycopg.connect(env["DB_OPERATOR_MANAGEMENT_DSN"], autocommit=True) as conn:
        conn.execute(
            sql.SQL("CREATE ROLE {} LOGIN PASSWORD {}").format(
                sql.Identifier(manager_role), sql.Literal(manager_password)
            )
        )
        conn.execute(
            sql.SQL("CREATE DATABASE {} OWNER {}").format(
                sql.Identifier(database), sql.Identifier(manager_role)
            )
        )
    binding = cfg["bindings"]["binding:appdb"]
    binding["alias"] = alias
    ini = Path(binding["config_path"])
    parser = configparser.ConfigParser(interpolation=None)
    parser.read(ini)
    parser["databases"][alias] = f"host=source port=5432 dbname={database}"
    with ini.open("w") as stream:
        parser.write(stream)
    with (ini.parent / "userlist.txt").open("a") as stream:
        stream.write(f'"{writer}" "{password}"\n')
    probe = make_conninfo(env["LAB_POOLER_APP"], dbname=alias, user=writer, password=password)
    monkeypatch.setenv("LAB_POOLER_APP", probe)
    registry_file = tmp_path / "registry.json"
    registry_file.write_text(json.dumps(cfg))
    settings = Settings(
        management_dsn=SecretStr(manager),
        api_token=SecretStr(env["DB_OPERATOR_API_TOKEN"]),
        registry=registry_file,
        retention_seconds=0,
    )
    service = Service(settings)
    service.store.initialize()
    service.driver.admin(service.registry.bindings["binding:appdb"], "RELOAD")
    return settings, service, SecretStr(probe)
